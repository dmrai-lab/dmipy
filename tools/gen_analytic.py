"""Generate docs/analytic/forms.md: every public form of the installed dmipy-analytic, module by module, with the
first paragraph of its docstring, the source the docstring cites and whether ``dmipy_analytic.jax`` holds its twin.

The table is read from the package and nothing is typed here, so a form added, renamed or re-cited there is a
regeneration away from the page.

Run:  python tools/gen_analytic.py
"""
from __future__ import annotations

import importlib
import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "analytic" / "forms.md"

MODULES = [
    ("constants", "The physical constants"),
    ("harmonics", "The real spherical-harmonic basis"),
    ("orientation", "Orientation distributions"),
    ("gaussian", "Gaussian diffusion"),
    ("restricted.plane", "Restriction: the plane"),
    ("restricted.cylinder", "Restriction: the cylinder"),
    ("restricted.sphere", "Restriction: the sphere"),
    ("restricted.matrix_method", "Restriction: the eigenmode (matrix) method"),
    ("exchange", "Exchange"),
    ("relaxation", "Relaxation and magnetization transfer"),
    ("epg", "Extended phase graphs"),
    ("fields", "The fields of simple shapes"),
]
SOURCE = re.compile(r"Sources?:\s*(.+?)(?:\n\s*\n|\Z)", re.S)
ROLE = re.compile(r":(?:mod|func|class|meth|attr|data):`~?([^`]+)`")


def one_line(text: str) -> str:
    """One table cell: whitespace collapsed, a Sphinx cross-reference as inline code, a pipe escaped."""
    return ROLE.sub(r"`\1`", re.sub(r"\s+", " ", text)).strip().replace("|", "\\|")


def summary(doc: str) -> str:
    return one_line(doc.split("\n\n")[0]) if doc else ""


def source(doc: str) -> str:
    m = SOURCE.search(doc or "")
    return one_line(m.group(1)) if m else ""


def forms(module):
    """The public functions and classes ``module`` defines (not those it imports), in source order."""
    out = []
    for name, obj in vars(module).items():
        if name.startswith("_") or not (inspect.isfunction(obj) or inspect.isclass(obj)):
            continue
        if getattr(obj, "__module__", None) != module.__name__:
            continue
        out.append((inspect.getsourcelines(obj)[1], name, obj))
    return [(name, obj) for _, name, obj in sorted(out)]


def twin(path: str, name: str) -> bool:
    try:
        return hasattr(importlib.import_module(f"dmipy_analytic.jax.{path}"), name)
    except ImportError:
        return False


def main() -> int:
    import dmipy_analytic
    lines = [
        "<!-- generated by tools/gen_analytic.py from the installed dmipy-analytic; regenerate, do not edit -->",
        "# Every form and its source",
        "",
        f"The public forms of dmipy-analytic {dmipy_analytic.__version__}, module by module: what each one is (the first "
        "paragraph of its docstring), the source its docstring cites, and whether `dmipy_analytic.jax` holds its JAX "
        "twin. The docstrings carry the assumptions each form holds under and its parameters.",
        "",
    ]
    n_forms = n_twins = 0
    for path, title in MODULES:
        module = importlib.import_module(f"dmipy_analytic.{path}")
        lines += [f"## {title}: `dmipy_analytic.{path}`", "", summary(inspect.getdoc(module) or ""), ""]
        if path == "constants":
            lines += ["| constant | value |", "|---|---|"]
            for name in ("GAMMA", "GAMMA_BAR", "MU0"):
                lines.append(f"| `{name}` | {getattr(module, name)!r} |")
            lines.append("")
            continue
        rows = forms(module)
        if not rows:
            continue
        lines += ["| form | what it is | source | JAX |", "|---|---|---|:---:|"]
        for name, obj in rows:
            doc = inspect.getdoc(obj) or ""
            has_twin = twin(path, name)
            n_forms += 1
            n_twins += has_twin
            lines.append(f"| `{name}` | {summary(doc)} | {source(doc)} | {'✓' if has_twin else ''} |")
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {n_forms} forms, {n_twins} with a JAX twin")
    return 0


if __name__ == "__main__":
    sys.exit(main())
